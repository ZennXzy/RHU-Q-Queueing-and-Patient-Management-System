document.addEventListener('DOMContentLoaded', () => {
    const searchInput = document.getElementById('appointmentSearch');

    const containers = [
        document.getElementById('pendingAppointmentsList'),
        document.getElementById('approvedAppointmentsList')
    ];

    if (!searchInput) return;

    function filterAppointments() {
        const searchValue = searchInput.value
            .trim()
            .toLowerCase()
            .replace(/\s+/g, ' ');

        containers.forEach(container => {
            if (!container) return;

            // Support multiple possible card class names generated by AJAX loaders
            const cards = container.querySelectorAll('.appointment-item, .appointment-card, .list-item');
            let visibleCount = 0;

            cards.forEach(card => {
                // Support multiple possible name selectors or fallback to full card text
                const nameElement = card.querySelector('.patient-name, .name, h3, strong');
                const targetText = nameElement ? nameElement.textContent : card.textContent;

                const normalizedText = targetText
                    .trim()
                    .toLowerCase()
                    .replace(/\s+/g, ' ');

                const isMatch = normalizedText.includes(searchValue);

                card.style.display = isMatch ? '' : 'none';
                if (isMatch) {
                    visibleCount++;
                }
            });

            // Handle search-specific empty message without breaking card layouts
            let searchEmptyMsg = container.querySelector('.search-empty-message');
            
            if (searchValue !== '' && cards.length > 0 && visibleCount === 0) {
                if (!searchEmptyMsg) {
                    searchEmptyMsg = document.createElement('div');
                    searchEmptyMsg.className = 'empty-state search-empty-message';
                    searchEmptyMsg.style.cssText = 'text-align: center; padding: 30px; color: #6b7280; font-size: 14px;';
                    searchEmptyMsg.innerHTML = '<p style="margin: 0;">No matching appointment records found.</p>';
                    container.appendChild(searchEmptyMsg);
                } else {
                    searchEmptyMsg.style.display = 'block';
                }
            } else if (searchEmptyMsg) {
                searchEmptyMsg.style.display = 'none';
            }
        });
    }

    // Filter immediately while typing
    searchInput.addEventListener('input', filterAppointments);
    searchInput.addEventListener('keyup', filterAppointments);

    // Reapply filter automatically after AJAX list updates or DOM changes
    containers.forEach(container => {
        if (!container) return;

        const observer = new MutationObserver(() => {
            filterAppointments();
        });

        observer.observe(container, {
            childList: true,
            subtree: true
        });
    });

    // Initial filter check
    filterAppointments();
});